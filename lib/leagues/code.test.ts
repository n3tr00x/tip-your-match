import { describe, expect, it } from 'vitest';

import { generateLeagueCode, normalizeLeagueCode } from '@/lib/leagues/code';
import { CODE_ALPHABET, CODE_LENGTH } from '@/lib/leagues/rules';

describe('generateLeagueCode', () => {
	// Randomness cannot be asserted directly, so check the invariants on many samples
	const codes = Array.from({ length: 200 }, generateLeagueCode);

	it(`always generates ${CODE_LENGTH} characters`, () => {
		expect(codes.every((code) => code.length === CODE_LENGTH)).toBe(true);
	});

	it('uses only characters from the code alphabet', () => {
		const usedCharacters = new Set(codes.join(''));

		expect([...usedCharacters].every((character) => CODE_ALPHABET.includes(character))).toBe(true);
	});

	it('never uses characters easily confused with 0 and 1', () => {
		expect(codes.join('')).not.toMatch(/[01]/);
	});
});

describe('normalizeLeagueCode', () => {
	it.each([
		{ input: 'ABC234', expected: 'ABC234' },
		{ input: 'abc234', expected: 'ABC234' },
		{ input: '  abc 234  ', expected: 'ABC234' },
		{ input: 'AB\tC2\n34', expected: 'ABC234' },
	])('normalizes "$input" to "$expected"', ({ input, expected }) => {
		expect(normalizeLeagueCode(input)).toBe(expected);
	});

	it('returns codes generated by the app unchanged', () => {
		const code = generateLeagueCode();

		expect(normalizeLeagueCode(code)).toBe(code);
	});
});
